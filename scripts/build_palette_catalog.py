def _generate_glasbey_white_bg(n: int = 32) -> list[str]:
    """Deterministic white-background Glasbey sequence in OKLCH (Glasbey et al., 2007)."""
    grid_rgb: list[np.ndarray] = []
    grid_hex: list[str] = []
    seen: set[str] = set()
    for L in np.linspace(0.32, 0.78, 12):
        for C in np.linspace(0.065, 0.185, 7):
            for h in np.linspace(0.0, 360.0, 36, endpoint=False):
                hx = oklch_to_hex(float(L), float(C), float(h))
                if hx not in seen:
                    seen.add(hx)
                    grid_hex.append(hx)
                    grid_rgb.append(hex_to_srgb01(hx))
    cand_arr = np.stack(grid_rgb, axis=0)
    white = np.array([[1.0, 1.0, 1.0]], dtype=np.float64)
    d_white = ciede2000_matrix(cand_arr, white)[:, 0]
    valid_mask = d_white >= 18.0
    cand_arr = cand_arr[valid_mask]
    cand_hex = [h for h, ok in zip(grid_hex, valid_mask) if ok]

    # Seed with maximally crisp dark-blue anchor, then greedy max-min CIEDE2000
    chosen_idx = [int(np.argmax(d_white[valid_mask]))]
    min_dists = ciede2000_matrix(cand_arr, cand_arr[[chosen_idx[0]]])[:, 0]
    for _ in range(1, n):
        nxt = int(np.argmax(min_dists))
        chosen_idx.append(nxt)
        d_new = ciede2000_matrix(cand_arr, cand_arr[[nxt]])[:, 0]
        min_dists = np.minimum(min_dists, d_new)
    return [cand_hex[i] for i in chosen_idx]


