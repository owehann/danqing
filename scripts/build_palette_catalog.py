def main() -> int:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    written = 0
    for entry in CATALOG:
        obj = dict(entry)
        obj.setdefault("qc", {})
        out_path = DATA_DIR / f"{obj['id']}.json"
        out_path.write_text(json.dumps(obj, indent=2, ensure_ascii=False) + "\n")
        written += 1
    total_json = len(list(DATA_DIR.glob("*.json")))
    print(f"[build_palette_catalog] Wrote {written} catalog JSONs; total palettes in data/ = {total_json}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
